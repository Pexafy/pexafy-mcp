    """The table as the grid's script declares it: the English texts once (`k`), then
    each language's in the same order (`t`) — every key written 22 times was half the
    weight. The script builds its lookup from it (I18N in widget.py)."""
    rows = {lang: [table[key] for key in KEYS] for lang, table in sorted(TRANSLATIONS.items())}
    return json.dumps({"k": list(KEYS), "t": rows}, ensure_ascii=False, separators=(",", ":"))


